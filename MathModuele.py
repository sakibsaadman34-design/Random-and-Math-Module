import math
print(f"The value of floor and ceiling of 23.56 are: {math.ceil(23.56)} and {math.floor(23.56)}")

x = 24

y = -15

print(f"The value of x after copying the sign from y is: {int(math.copysign(x, y))}")

print(f"The absolute value of x and y are: {int(math.fabs(x))} and {int(math.fabs(y))}")

print(f"The GCD of 24 and 56 are: {int(math.gcd(24, 56))}")